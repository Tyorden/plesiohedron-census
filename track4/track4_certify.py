def derive_lattice_cosets(base, P):
    """Primitive translation lattice of the periodic set base mod P — same
    contract as mint_tables.derive_lattice (returns (B columns int, detL>0)),
    but COMPLETE by a coset argument instead of a P^3 grid scan (the original
    enumerates range(-P,P+1)^3, infeasible for the Engel cell's P = 6984):
    any translation t with S + t = S maps base[0] to some site, so
    t == base[j] - base[0] (mod P Z^3) for some j.  Hence L is generated by
    P e_i together with those of the n deltas d_j = base[j]-base[0] (mod P)
    that preserve S mod P.  A triple of generators spans L iff it integrally
    spans every generator; a spanning triple has |det| = covol(L)."""
    from itertools import combinations
    from mint_tables import det3, mat_inv, mat_vec, to_int_mat
    baseset = set((x % P, y % P, z % P) for x, y, z in base)
    b0 = base[0]
    gens = [(P, 0, 0), (0, P, 0), (0, 0, P)]
    for q in base:
        d = tuple((q[i] - b0[i]) % P for i in range(3))
        if d == (0, 0, 0):
            continue
        if set(((x+d[0]) % P, (y+d[1]) % P, (z+d[2]) % P)
               for x, y, z in base) == baseset:
            # symmetric representative (shortest coset member) for the search
            gens.append(tuple(c - P if c > P // 2 else c for c in d))
    short = sorted(set(gens), key=lambda t: (sum(x*x for x in t), t))[:20]
    for a, b, c in combinations(short, 3):
        dd = det3(a, b, c)
        if dd == 0:
            continue
        Bcols = [[F(a[i]), F(b[i]), F(c[i])] for i in range(3)]
        Binv = mat_inv(Bcols)
        if all(all(F(x).denominator == 1 for x in mat_vec(Binv, t))
               for t in gens):
            return to_int_mat(Bcols), abs(dd)
    raise AssertionError("no primitive basis found among shortest translations")


# Self-check on a feasible period: coset version == original grid version.
def _selfcheck_lattice(pts, P):
    from mint_tables import derive_lattice as _orig
    B1, d1 = derive_lattice_cosets(pts, P)
    B2, d2 = _orig(pts, P)
    assert d1 == d2, "coset lattice derivation disagrees with grid version (det)"
    # same lattice: each basis integrally expresses the other
    from mint_tables import mat_inv, mat_vec
    for Ba, Bb in ((B1, B2), (B2, B1)):
        Binv = mat_inv([[F(Ba[i][j]) for j in range(3)] for i in range(3)])
        for j in range(3):
            v = tuple(Bb[i][j] for i in range(3))
            assert all(F(x).denominator == 1 for x in mat_vec(Binv, v)), \
                "coset lattice != grid lattice"
    return d1


